/**
 * FLOW 05 — Notifications Verification Seeding Bot
 * ============================================================
 * Exercises public HTTP/API endpoints:
 * 1. Authenticate seed users via /api/auth/login
 * 2. Query notifications via GET /api/notifications
 * 3. Verify notification event propagation from social & engagement flows
 * 4. Update unread/read state via PATCH /api/notifications
 *
 * Usage:
 *   node seeding_scripts/05_notifications_flow/bot.js
 * ============================================================
 */

const fs = require('fs');
const path = require('path');
const { HttpClient } = require('../shared/http');

const INPUT_PATH = path.join(__dirname, '..', 'data_input.json');
const SESSION_PATH = path.join(__dirname, '..', 'session_state.json');
const FLOW_SESSION_PATH = path.join(__dirname, 'session_state.json');

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function loadInput() {
  if (!fs.existsSync(INPUT_PATH)) {
    throw new Error(`FLOW 05 ERROR: Master data_input.json not found at ${INPUT_PATH}`);
  }
  return JSON.parse(fs.readFileSync(INPUT_PATH, 'utf8'));
}

function loadSession() {
  const paths = [
    path.join(__dirname, '..', 'session_state.json'),
    path.join(__dirname, 'session_state.json'),
    path.join(__dirname, '..', '01_auth_profile_flow', 'session_state.json')
  ];
  for (const p of paths) {
    if (fs.existsSync(p)) {
      return JSON.parse(fs.readFileSync(p, 'utf8'));
    }
  }
  throw new Error('FLOW 05 FAILED: Prerequisite session_state.json missing. Run Flows 01, 03, & 04 first.');
}

function saveSession(sessionData) {
  fs.writeFileSync(SESSION_PATH, JSON.stringify(sessionData, null, 2));
  fs.writeFileSync(FLOW_SESSION_PATH, JSON.stringify(sessionData, null, 2));
}

async function runNotificationsFlow() {
  console.log('🚀 FLOW 05: Notifications Verification starting...\n');

  const inputData = loadInput();
  const sessionData = loadSession();
  const env = inputData.env || { BFF_URL: 'http://localhost:3000/api', THROTTLE_MS: 300 };
  // URL VAR FOR LOCAL (Host native / localhost)
  // BFF_URL="http://localhost:3000/api"
  // URL VAR FOR PROD (Container network / VPS)
  // BFF_URL="https://www.vibegrid.manakhly.tech/api"
  const bffUrl = process.env.API_URL || process.env.BFF_URL || env.BFF_URL || env.API_URL || 'http://localhost:3000/api';
  console.log(`📡 Ingress API Target: ${bffUrl}`);

  // 1. Validate Prerequisite State
  const seedUsers = inputData.users || [];
  for (const u of seedUsers) {
    if (!sessionData[u.id] || !sessionData[u.id].userId) {
      throw new Error(`FLOW 05 FAILED: Missing prerequisite user session for ${u.id}. Please execute Flow 01 first.`);
    }
  }

  // 2. Authenticate Users via HTTP API
  const userClients = {};
  for (const u of seedUsers) {
    const client = new HttpClient(bffUrl);
    console.log(`[FLOW 05] Authenticating user ${u.email}...`);
    const loginRes = await client.post('/auth/login', {
      email: u.email,
      password: u.password,
    });

    if (!loginRes.ok || !loginRes.data?.success) {
      throw new Error(`FLOW 05 FAILED: HTTP Login failed for ${u.email}: ${JSON.stringify(loginRes.data || loginRes.rawBody)}`);
    }

    userClients[u.id] = client;
    console.log(`   ✓ Authenticated ${u.profile.username} via HTTP API`);
  }

  sessionData.notifications = sessionData.notifications || {};
  sessionData.bookmarks = sessionData.bookmarks || [];

  // 3. Seed Bookmarks (Saved Posts) via HTTP API
  if (Array.isArray(inputData.bookmarks) && inputData.bookmarks.length > 0) {
    console.log('\n[FLOW 05] Seeding Bookmarks (Saved Posts)...');
    for (const bSpec of inputData.bookmarks) {
      const userClient = userClients[bSpec.userRef];
      const postSession = sessionData.posts?.[bSpec.postRef];
      const userSession = sessionData[bSpec.userRef];

      if (userClient && postSession) {
        console.log(`   🔖 User ${userSession.username} bookmarking post ${postSession.id.substring(0, 8)}...`);
        const bRes = await userClient.post(`/posts/${postSession.id}/bookmark`);
        if (!bRes.ok) {
          console.warn(`   ⚠️ Bookmark response notice:`, bRes.data || bRes.rawBody);
        } else {
          console.log(`   ✓ Bookmarked successfully`);
          sessionData.bookmarks.push({
            userRef: bSpec.userRef,
            postRef: bSpec.postRef,
            postId: postSession.id,
          });
        }
        await sleep(env.THROTTLE_MS || 300);
      }
    }
    // Pop bookmarks from consumable queue
    inputData.bookmarks = [];
    fs.writeFileSync(INPUT_PATH, JSON.stringify(inputData, null, 2));
  } else {
    console.log('   ℹ No bookmarks to seed in data_input.json (already seeded or empty).');
  }

  // 4. Query & Verify Notifications for Each Seed User
  console.log('\n[FLOW 05] Verifying notifications generated by seeding actions...');
  for (const u of seedUsers) {
    const userClient = userClients[u.id];
    const userSession = sessionData[u.id];

    console.log(`[FLOW 05] Fetching notifications for ${userSession.username}...`);
    const notifRes = await userClient.get('/notifications');

    if (!notifRes.ok || (!notifRes.data?.success && !Array.isArray(notifRes.data?.notifications))) {
      throw new Error(`FLOW 05 FAILED: Unable to fetch notifications for ${userSession.username} (HTTP ${notifRes.status}): ${JSON.stringify(notifRes.data || notifRes.rawBody)}`);
    }

    const notificationsList = notifRes.data.notifications || [];
    console.log(`   ✓ Found ${notificationsList.length} notification(s) for ${userSession.username}`);

    sessionData.notifications[u.id] = {
      count: notificationsList.length,
      items: notificationsList.map((n) => ({
        id: n.id,
        type: n.type,
        actorId: n.actorId || n.issuerId || null,
        read: n.isRead || n.read || false,
        createdAt: n.createdAt,
      })),
    };

    // Test marking notifications as read if unread exist
    const unreadIds = notificationsList.filter((n) => !n.isRead && !n.read).map((n) => n.id);
    if (unreadIds.length > 0) {
      console.log(`   ✉ Marking ${unreadIds.length} notification(s) as read for ${userSession.username}...`);
      const patchRes = await userClient.patch('/notifications', { notificationIds: unreadIds });
      if (patchRes.ok && patchRes.data?.success) {
        console.log(`   ✓ Successfully marked notifications as read via HTTP API`);
      } else {
        console.warn(`   ⚠️ Mark as read response:`, patchRes.data);
      }
    }

    await sleep(env.THROTTLE_MS || 300);
  }

  saveSession(sessionData);
  console.log('\n🎉 FLOW 05: Notifications Verification complete!\n');
}

runNotificationsFlow()
  .catch((err) => {
    console.error('\n❌ FLOW 05 Failed:', err.message);
    process.exit(1);
  });
